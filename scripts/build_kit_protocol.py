"""Write web/kit-protocol.md: the five role prompts of the agent, as one file a user's own agent can follow.

  python scripts/build_kit_protocol.py
The viewer fills this in with the paper and the job credentials and publishes it as a plain-text link
(see web/kit.js). Source of truth stays repro/prompts.py, so the kit and the hosted agent never drift.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from repro import prompts as P  # noqa: E402

ROLES = [
    ("1. READER (read the paper, write the claim contract)", P.READER),
    ("2. ROUTER (what did the authors release, can this machine run it)", P.ROUTER),
    ("3. PLANNER (files, config, smoke test, checks)", P.PLANNER),
    ("4. IMPLEMENTER (write and run the code until one command re-creates the number)", P.EXECUTOR),
    ("5. VERIFIER (delete results, re-run from scratch, audit)", P.VERIFIER),
]
out = ["<!-- generated by scripts/build_kit_protocol.py from repro/prompts.py; do not edit -->", ""]
for title, body in ROLES:
    out += [f"### {title}", "", "~~~text", body.strip(), "~~~", ""]
(ROOT / "web" / "kit-protocol.md").write_text("\n".join(out), encoding="utf-8")
print("wrote web/kit-protocol.md", sum(len(b) for _, b in ROLES), "chars of prompts")

# the hosted steps 1 to 3 (supabase/functions/run-steps) read the same prompts
import json  # noqa: E402

fn = ROOT / "supabase" / "functions" / "run-steps"
fn.mkdir(parents=True, exist_ok=True)
(fn / "prompts.json").write_text(json.dumps({
    "READER": P.READER, "ROUTER": P.ROUTER.replace("{wall_minutes}", "60"), "PLANNER": P.PLANNER, "VERIFIER": P.VERIFIER,
}, ensure_ascii=False, indent=1), encoding="utf-8")
print("wrote", fn / "prompts.json")

# the machine probe the kit tells the agent to run (Step 0); same file as repro/probe.py
(ROOT / "web" / "kit-probe.py").write_text((ROOT / "repro" / "probe.py").read_text(encoding="utf-8"), encoding="utf-8")
print("wrote web/kit-probe.py")
